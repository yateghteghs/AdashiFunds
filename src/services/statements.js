'use strict';
const PDFDocument = require('pdfkit');
const db = require('../db');
const ledger = require('./ledger');
const wallet = require('./wallet');
const { bad } = require('../lib/errors');

const naira = (k) => `NGN ${(k / 100).toLocaleString('en-NG', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

function monthRange(month) {
  if (!/^\d{4}-\d{2}$/.test(month)) throw bad('invalid_month', 'Month must be YYYY-MM');
  const [y, m] = month.split('-').map(Number);
  return { from: new Date(Date.UTC(y, m - 1, 1)).toISOString(), to: new Date(Date.UTC(y, m, 1)).toISOString() };
}

function build(userId, { from, to }) {
  const acct = ledger.userAccount(userId);
  const opening = db.get('SELECT COALESCE(SUM(amount),0) AS s FROM ledger_entries WHERE account_id = ? AND created_at < ?', acct.id, from).s;
  const rows = wallet.history(userId, { from, to, limit: 10_000 }).reverse();
  const net = rows.reduce((s, r) => s + r.net, 0);
  const totals = {};
  for (const r of rows) {
    if (r.status !== 'success' && r.net === 0) continue;
    const key = r.type === 'transfer' ? (r.net >= 0 ? 'transfers_in' : 'transfers_out') : r.type;
    totals[key] = (totals[key] || 0) + Math.abs(r.net);
  }
  return { from, to, openingBalance: opening, closingBalance: opening + net, totals, rows };
}

function monthlySummary(userId, month) {
  const s = build(userId, monthRange(month));
  return {
    month, openingBalance: s.openingBalance, closingBalance: s.closingBalance,
    contributed: s.totals.contribution || 0, payoutsReceived: s.totals.payout || 0, deposits: s.totals.deposit || 0,
    withdrawals: s.totals.withdrawal || 0, transfersIn: s.totals.transfers_in || 0, transfersOut: s.totals.transfers_out || 0,
    loanDisbursements: s.totals.loan_disbursement || 0, loanRepayments: s.totals.loan_repayment || 0,
    penaltiesPaid: s.rows.filter((r) => r.type === 'contribution').reduce((a, r) => a + (r.fee || 0), 0),
    transactionCount: s.rows.length,
  };
}

const csvCell = (v) => {
  const s = v == null ? '' : String(v);
  // Neutralise spreadsheet formula injection and quote when needed.
  const safe = /^[=+\-@\t\r]/.test(s) ? `'${s}` : s;
  return /[",\n]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
};

function toCsv(userId, range) {
  const s = build(userId, range);
  const header = ['date', 'reference', 'type', 'description', 'status', 'amount_ngn', 'fee_ngn', 'wallet_effect_ngn'];
  const lines = [header.join(',')];
  for (const r of s.rows) {
    lines.push([r.created_at, r.reference, r.type, r.description, r.status, (r.amount / 100).toFixed(2), (r.fee / 100).toFixed(2), (r.net / 100).toFixed(2)].map(csvCell).join(','));
  }
  return lines.join('\n') + '\n';
}

function toPdf(userId, range) {
  const user = db.get('SELECT full_name, phone, email FROM users WHERE id = ?', userId);
  const s = build(userId, range);
  const doc = new PDFDocument({ size: 'A4', margin: 40 });
  const chunks = [];
  doc.on('data', (c) => chunks.push(c));
  const done = new Promise((resolve) => doc.on('end', () => resolve(Buffer.concat(chunks))));

  doc.fontSize(18).text('AdashiFunds Wallet Statement');
  doc.moveDown(0.3).fontSize(10).fillColor('#555')
    .text(`${user.full_name} · ${user.phone}${user.email ? ` · ${user.email}` : ''}`)
    .text(`Period: ${s.from.slice(0, 10)} to ${s.to.slice(0, 10)}`);
  doc.moveDown().fillColor('#000').fontSize(11)
    .text(`Opening balance: ${naira(s.openingBalance)}`)
    .text(`Closing balance: ${naira(s.closingBalance)}`);
  doc.moveDown();

  const cols = [40, 115, 205, 400, 480];
  const head = (y) => {
    doc.fontSize(9).font('Helvetica-Bold');
    ['Date', 'Type', 'Description', 'Status', 'Effect'].forEach((h, i) => doc.text(h, cols[i], y));
    doc.font('Helvetica');
  };
  let y = doc.y;
  head(y);
  y += 16;
  for (const r of s.rows) {
    if (y > 780) { doc.addPage(); y = 40; head(y); y += 16; }
    doc.fontSize(8)
      .text(r.created_at.slice(0, 10), cols[0], y)
      .text(r.type, cols[1], y)
      .text((r.description || '').slice(0, 45), cols[2], y, { width: 190 })
      .text(r.status, cols[3], y)
      .text(naira(r.net), cols[4], y);
    y += 14;
  }
  if (!s.rows.length) doc.fontSize(10).text('No transactions in this period.', 40, y);
  doc.moveDown(2).fontSize(7).fillColor('#777').text('Generated by AdashiFunds. Every entry is backed by the double-entry ledger and tamper-evident audit log.', 40);
  doc.end();
  return done;
}

module.exports = { build, monthRange, monthlySummary, toCsv, toPdf };
